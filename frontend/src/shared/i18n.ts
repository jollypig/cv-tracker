export type TranslationKey = string

function storedLocale(): Locale {
  try {
    const value = localStorage.getItem(storageKey)
    return locales.find((locale) => locale === value) ?? 'en'
  } catch {
    return 'en'
  }
}

export const locale = ref<Locale>(storedLocale())
if (typeof document !== 'undefined') document.documentElement.lang = locale.value

export function setLocale(value: Locale): void {
  locale.value = value
  if (typeof document !== 'undefined') document.documentElement.lang = value
  try {
    localStorage.setItem(storageKey, value)
  } catch {
    // Keep the selected locale in memory when browser storage is unavailable.
  }
}

export function translate(key: TranslationKey, values: Record<string, string | number> = {}): string {
  const message = messages[locale.value][key] ?? key
  return message.replace(/\{(\w+)\}/g, (match: string, name: string) => String(values[name] ?? match))
}